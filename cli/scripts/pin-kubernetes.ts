/** Lines removed from `before` (-) and added by `after` (+), from a longest-common-subsequence walk. */
function formatDiff(before: string, after: string, limit = 80): string {
  const a = before.split('\n');
  const b = after.split('\n');
  const common = Array.from({ length: a.length + 1 }, () => new Uint32Array(b.length + 1));
  for (let i = a.length - 1; i >= 0; i--) {
    for (let j = b.length - 1; j >= 0; j--) {
      common[i][j] = a[i] === b[j] ? common[i + 1][j + 1] + 1 : Math.max(common[i + 1][j], common[i][j + 1]);
    }
  }
  const lines: string[] = [];
  let i = 0;
  let j = 0;
  while (i < a.length || j < b.length) {
    if (i < a.length && j < b.length && a[i] === b[j]) {
      i++;
      j++;
    } else if (i < a.length && (j === b.length || common[i + 1][j] >= common[i][j + 1])) {
      lines.push(`-${i + 1}: ${a[i]}`);
      i++;
    } else {
      lines.push(`+${j + 1}: ${b[j]}`);
      j++;
    }
  }
  if (lines.length <= limit) return lines.join('\n');
  return [...lines.slice(0, limit), `... ${lines.length - limit} more changed lines`].join('\n');
}

function normalizeEol(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

/** A sha256 that changed while its version did not: a re-published or tampered artifact. */
function changedUnderSameVersion(committed: Committed, pins: Pins): string[] {
  const problems: string[] = [];
  const compare = (what: string, before: string | undefined, after: string): void => {
    if (before !== undefined && before !== after) problems.push(`${what} changed without a version change: committed ${before}, published ${after}`);
  };
  const k3s = committed.k3s;
  if (k3s !== undefined && k3s.version === pins.k3s.version) {
    compare(`k3s ${k3s.version} install.sh`, k3s.installScript?.sha256, pins.k3s.installScript.sha256);
    for (const arch of ARCHES) compare(`k3s ${k3s.version} ${arch} binary`, k3s.binaries?.[arch]?.sha256, pins.k3s.binaries[arch].sha256);
  }
  const helm = committed.helm;
  if (helm !== undefined && helm.version === pins.helm.version) {
    for (const arch of ARCHES) compare(`Helm ${helm.version} ${arch} archive`, helm.archives?.[arch]?.sha256, pins.helm.archives[arch].sha256);
  }
  const traefik = committed.traefik;
  if (traefik !== undefined && traefik.version === pins.traefik.version) {
    compare(`Traefik chart ${traefik.version} archive`, traefik.sha256, pins.traefik.sha256);
  }
  return problems;
}

async function verifyK3sBinaries(k3s: K3sPins): Promise<string[]> {
  const problems: string[] = [];
  for (const arch of ARCHES) {
    const pin = k3s.binaries[arch];
    step(`re-hashing ${pin.url}`);
    const actual = sha256Hex(await fetchBytes(pin.url));
    if (actual !== pin.sha256) problems.push(`k3s ${k3s.version} ${arch}: the download hashes to ${actual}, sha256sum-${arch}.txt says ${pin.sha256}`);
  }
  return problems;
}

function reportCheck(outputs: Output[], problems: string[]): number {
  let failed = problems.length > 0;
  for (const problem of problems) out(`mismatch: ${problem}`);
  for (const output of outputs) {
    const label = repoPath(output.path);
    const committed = existsSync(output.path) ? normalizeEol(readFileSync(output.path, 'utf8')) : null;
    const expected = normalizeEol(output.content);
    if (committed === expected) {
      out(`ok       ${label}`);
      continue;
    }
    failed = true;
    if (committed === null) {
      out(`missing  ${label}`);
      continue;
    }
    out(`differs  ${label} (- committed, + regenerated)`);
    out(formatDiff(committed, expected));
  }
  out(failed ? 'The committed pins are out of date.' : 'The committed pins are up to date.');
  return failed ? 1 : 0;
}

