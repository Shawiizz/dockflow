const VALUE_FLAGS = new Set(['--k3s', '--helm', '--traefik-chart', '--minimum-server', '--resolve-channel']);
const BOOLEAN_FLAGS = new Set(['--check', '--verify', '--check-updates', '--markdown', '--no-docs', '--repin-image', '--help']);
const PIN_FLAGS = ['--k3s', '--helm', '--traefik-chart', '--minimum-server', '--check', '--no-docs', '--repin-image'];
const EXCLUSIVE_FLAGS = ['--verify', '--check-updates', '--resolve-channel'];
const CHANNELS = ['minimum', 'latest', 'stable'];

function parseArgs(argv: string[]): Options {
  const values = new Map<string, string>();
  const flags = new Set<string>();
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const eq = arg.indexOf('=');
    const name = eq > 0 ? arg.slice(0, eq) : arg;
    if (VALUE_FLAGS.has(name)) {
      const value = eq > 0 ? arg.slice(eq + 1) : argv[++i];
      if (value === undefined || value === '' || value.startsWith('--')) throw new UsageError(`${name} needs a value`);
      if (values.has(name)) throw new UsageError(`${name} is given twice`);
      values.set(name, value);
    } else if (BOOLEAN_FLAGS.has(arg)) {
      flags.add(arg);
    } else {
      throw new UsageError(`Unknown argument ${arg}`);
    }
  }
  const given = (flag: string): boolean => flags.has(flag) || values.has(flag);
  const exclusive = EXCLUSIVE_FLAGS.filter(given);
  const pinFlags = PIN_FLAGS.filter(given);
  if (exclusive.length > 1) throw new UsageError(`${exclusive.join(' and ')} cannot be combined`);
  if (exclusive.length === 1 && pinFlags.length > 0) {
    throw new UsageError(`${pinFlags[0]} cannot be combined with ${exclusive[0]}`);
  }
  if (flags.has('--markdown') && exclusive[0] !== '--check-updates') {
    throw new UsageError('--markdown only applies to --check-updates');
  }
  const channel = values.get('--resolve-channel');
  if (channel !== undefined && !CHANNELS.includes(channel)) {
    throw new UsageError(`--resolve-channel takes one of ${CHANNELS.join(', ')}, not ${channel}`);
  }
  const help = flags.has('--help');
  let mode: Mode = 'pin';
  if (exclusive[0] === '--verify') mode = 'verify';
  else if (exclusive[0] === '--check-updates') mode = 'check-updates';
  else if (exclusive[0] === '--resolve-channel') mode = 'resolve-channel';
  else if (pinFlags.length === 0 && !help) throw new UsageError('Nothing to do');
  return {
    mode,
    help,
    k3s: values.get('--k3s'),
    helm: values.get('--helm'),
    traefikChart: values.get('--traefik-chart'),
    minimumServer: values.get('--minimum-server'),
    channel,
    check: flags.has('--check'),
    noDocs: flags.has('--no-docs'),
    repinImage: flags.has('--repin-image'),
    markdown: flags.has('--markdown'),
  };
}

