async function importExport<T>(file: string, name: string): Promise<T | undefined> {
  if (!existsSync(file)) return undefined;
  try {
    const loaded: Record<string, unknown> = await import(pathToFileURL(file).href);
    return loaded[name] as T | undefined;
  } catch (error) {
    throw new PinError(`Could not load ${repoPath(file)}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function loadCommitted(): Promise<Committed> {
  return {
    k3s: await importExport<K3sPins>(K3S_VERSIONS_FILE, 'K3S_PIN'),
    helm: await importExport<HelmPins>(VERSIONS_FILE, 'HELM_PIN'),
    traefik: await importExport<TraefikPins>(VERSIONS_FILE, 'TRAEFIK_CHART_PIN'),
  };
}

function checkVersions(k3s: string, minimum: string, helm: string, chart: string): void {
  if (!K3S_VERSION_RE.test(k3s)) throw new PinError(`k3s version ${k3s} is not a k3s release such as v1.36.4+k3s1`);
  if (!PLAIN_VERSION_RE.test(minimum)) throw new PinError(`minimum server version ${minimum} is not a version such as v1.34.0`);
  if (!PLAIN_VERSION_RE.test(helm)) throw new PinError(`Helm version ${helm} is not a version such as v4.3.0`);
  if (!CHART_VERSION_RE.test(chart)) throw new PinError(`Traefik chart version ${chart} is not a version such as 41.6.0`);
  if (compareVersions(minimum, k3s) > 0) throw new PinError(`The minimum server version ${minimum} is newer than k3s ${k3s}`);
}

async function runPin(options: Options): Promise<number> {
  const verify = options.mode === 'verify';
  const committed = await loadCommitted();
  const k3sVersion = options.k3s ?? committed.k3s?.version;
  const minimum = options.minimumServer ?? committed.k3s?.minimumServerVersion;
  const helmVersion = options.helm ?? committed.helm?.version;
  const chartVersion = options.traefikChart ?? committed.traefik?.version;
  if (k3sVersion === undefined) throw new UsageError('--k3s is required: there is no committed k3s pin');
  if (minimum === undefined) throw new UsageError('--minimum-server is required: there is no committed minimum server version');
  if (helmVersion === undefined) throw new UsageError('--helm is required: there is no committed Helm pin');
  if (chartVersion === undefined) throw new UsageError('--traefik-chart is required: there is no committed Traefik chart pin');
  checkVersions(k3sVersion, minimum, helmVersion, chartVersion);

  const notes: string[] = [];
  const k3s = await resolveK3s(k3sVersion, minimum);
  const helm = await resolveHelm(helmVersion);
  const chart = await resolveTraefikChart(chartVersion);
  const imageDigest = await resolveImageDigest(chart.pin.appVersion, committed.traefik, options.repinImage, notes);
  const pins: Pins = { k3s, helm, traefik: { ...chart.pin, imageDigest } };
  const schema = middlewareSchema(chart);
  const problems = changedUnderSameVersion(committed, pins);
  if (verify) problems.push(...(await verifyK3sBinaries(k3s)));

  const outputs: Output[] = [
    { path: K3S_VERSIONS_FILE, content: renderK3sVersions(k3s) },
    { path: VERSIONS_FILE, content: renderVersions(helm, pins.traefik) },
    { path: CRD_SCHEMA_FILE, content: renderMiddlewareSchema(pins.traefik, schema) },
  ];
  const docs = options.noDocs ? null : docsOutput(pins, notes);
  if (docs !== null) outputs.push(docs);
  for (const note of notes) err(`note: ${note}`);

  if (options.check || verify) return reportCheck(outputs, problems);
  if (problems.length > 0) throw new PinError(['Refusing to rewrite the pins:', ...problems.map((problem) => `  ${problem}`)].join('\n'));
  for (const output of outputs) {
    const unchanged = existsSync(output.path) && normalizeEol(readFileSync(output.path, 'utf8')) === normalizeEol(output.content);
    if (!unchanged) {
      mkdirSync(dirname(output.path), { recursive: true });
      writeFileSync(output.path, output.content);
    }
    out(`${unchanged ? 'unchanged' : 'wrote    '} ${repoPath(output.path)}`);
  }
  out(
    `Pinned k3s ${k3s.version} (minimum ${k3s.minimumServerVersion}), Helm ${helm.version}, Traefik chart ${pins.traefik.version} (Traefik ${pins.traefik.appVersion}, ${imageDigest})`,
  );
  return 0;
}

async function k3sChannels(): Promise<Map<string, string>> {
  const body = asRecord(JSON.parse(await fetchText(K3S_CHANNELS)) as unknown, K3S_CHANNELS);
  if (!Array.isArray(body.data)) throw new PinError(`${K3S_CHANNELS} has no data`);
  const channels = new Map<string, string>();
  for (const channel of body.data as unknown[]) {
    if (isRecord(channel) && typeof channel.id === 'string' && typeof channel.latest === 'string') channels.set(channel.id, channel.latest);
  }
  return channels;
}

async function resolveChannel(channel: string): Promise<number> {
  let id = channel;
  if (channel === 'minimum') {
    const committed = await loadCommitted();
    if (committed.k3s === undefined) throw new PinError('There is no committed k3s pin to read the minimum server version from');
    id = minorChannel(committed.k3s.minimumServerVersion);
  }
  const version = (await k3sChannels()).get(id);
  if (version === undefined || !K3S_VERSION_RE.test(version)) throw new PinError(`The k3s ${id} channel has no release`);
  out(version);
  return 0;
}

async function latestHelm(): Promise<string> {
  const headers: Record<string, string> = { Accept: 'application/vnd.github+json' };
  const token = process.env.GITHUB_TOKEN;
  if (token) headers.Authorization = `Bearer ${token}`;
  const body: unknown = JSON.parse(await fetchText(HELM_LATEST_RELEASE, { headers }));
  const tag = isRecord(body) ? body.tag_name : undefined;
  if (typeof tag !== 'string' || !PLAIN_VERSION_RE.test(tag)) throw new PinError(`${HELM_LATEST_RELEASE} returned no release tag`);
  return tag;
}

async function latestTraefikChart(): Promise<{ version: string; appVersion: string }> {
  let latest: { version: string; appVersion: string } | null = null;
  for (const entry of await chartIndexEntries()) {
    if (!isRecord(entry) || typeof entry.version !== 'string' || !CHART_VERSION_RE.test(entry.version)) continue;
    if (latest !== null && compareVersions(entry.version, latest.version) <= 0) continue;
    latest = { version: entry.version, appVersion: typeof entry.appVersion === 'string' ? entry.appVersion : 'unknown' };
  }
  if (latest === null) throw new PinError(`${TRAEFIK_REPO}/index.yaml lists no ${TRAEFIK_CHART} release`);
  return latest;
}

async function checkUpdates(markdown: boolean): Promise<number> {
  const committed = await loadCommitted();
  const { k3s, helm, traefik } = committed;
  if (k3s === undefined || helm === undefined || traefik === undefined) throw new PinError('--check-updates needs committed pins');
  const channels = await k3sChannels();
  const helmLatest = await latestHelm();
  const chart = await latestTraefikChart();
  const tagDigest = await currentTagDigest(traefik.appVersion, await registryToken());
  const status = (pinned: string, available: string): string => (pinned === available ? 'up to date' : 'update available');
  const rows: string[][] = [
    ['k3s (stable channel)', k3s.version, channels.get('stable') ?? 'unknown'],
    ['k3s (latest channel)', k3s.version, channels.get('latest') ?? 'unknown'],
    ['Helm', helm.version, helmLatest],
    ['Traefik chart', traefik.version, chart.version],
    [`Traefik image ${traefik.appVersion}`, traefik.imageDigest ?? 'none', tagDigest],
  ].map(([component, pinned, available]) => [component, pinned, available, status(pinned, available)]);
  if (chart.version !== traefik.version) rows[3][2] = `${chart.version} (Traefik ${chart.appVersion})`;
  if (tagDigest !== traefik.imageDigest) rows[4][3] = 'tag rebuilt (--repin-image)';
  const header = ['Component', 'Pinned', 'Available', 'Status'];
  if (markdown) {
    out('### Kubernetes pins');
    out('');
    for (const row of [header, header.map(() => '---'), ...rows]) out(`| ${row.join(' | ')} |`);
    return 0;
  }
  const widths = header.map((_, column) => Math.max(...[header, ...rows].map((row) => row[column].length)));
  for (const row of [header, ...rows]) out(row.map((cell, column) => cell.padEnd(widths[column])).join('  ').trimEnd());
  return 0;
}

async function main(argv: string[]): Promise<number> {
  const options = parseArgs(argv);
  if (options.help) {
    out(USAGE);
    return 0;
  }
  switch (options.mode) {
    case 'pin':
    case 'verify':
      return runPin(options);
    case 'check-updates':
      return checkUpdates(options.markdown);
    case 'resolve-channel':
      return resolveChannel(options.channel ?? 'stable');
  }
}

if (import.meta.main) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error: unknown) => {
      if (error instanceof UsageError) {
        err(`${error.message}\n\n${USAGE}`);
        process.exitCode = 2;
        return;
      }
      err(`pin-kubernetes: ${error instanceof Error ? error.message : String(error)}`);
      process.exitCode = 1;
    },
  );
}
