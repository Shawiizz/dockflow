/** null when the page has no complete k3s-pins region */
function replaceDocsRegion(page: string, region: string): string | null {
  const crlf = page.includes('\r\n');
  const text = crlf ? page.replace(/\r\n/g, '\n') : page;
  const start = text.indexOf(DOCS_BEGIN);
  const end = start < 0 ? -1 : text.indexOf(DOCS_END, start);
  if (start < 0 || end < 0) return null;
  const replaced = text.slice(0, start) + region + text.slice(end + DOCS_END.length);
  return crlf ? replaced.replace(/\n/g, '\r\n') : replaced;
}

function docsOutput(pins: Pins, notes: string[]): Output | null {
  if (!existsSync(DOCS_PAGE)) {
    notes.push(`${repoPath(DOCS_PAGE)} does not exist; its k3s-pins region was not generated.`);
    return null;
  }
  const content = replaceDocsRegion(readFileSync(DOCS_PAGE, 'utf8'), renderDocsRegion(pins));
  if (content === null) {
    notes.push(`${repoPath(DOCS_PAGE)} has no ${DOCS_BEGIN} ... ${DOCS_END} region; it was not generated.`);
    return null;
  }
  return { path: DOCS_PAGE, content };
}

