#!/usr/bin/env bun
/**
 * Pins what Dockflow installs for Kubernetes (k3s, Helm, the Traefik chart and image) and generates
 * the files that carry those pins (DESIGN-CORE 8.7, design-04 2.14.1 and I14):
 *   src/services/orchestrator/kubernetes/k3s/versions.ts
 *   src/services/orchestrator/kubernetes/versions.ts
 *   src/services/orchestrator/kubernetes/traefik-crd-schema.generated.ts
 * and the `k3s-pins` region of the k3s setup docs page when that page exists.
 *
 * Usage (from cli/):
 *   bun run scripts/pin-kubernetes.ts --k3s <v> [--helm <v>] [--traefik-chart <v>] [--minimum-server <v>]
 *                                     [--repin-image] [--no-docs] [--check]
 *   bun run scripts/pin-kubernetes.ts --verify
 *   bun run scripts/pin-kubernetes.ts --check-updates [--markdown]
 *   bun run scripts/pin-kubernetes.ts --resolve-channel <minimum|latest|stable>
 *
 * A version left out keeps its committed value. Checksums come from two sources that must agree:
 * k3s binaries from the release's sha256sum-<arch>.txt (re-hashed by --verify), Helm archives from
 * their .sha256sum file and a local re-hash, the chart from the repository index digest and a local
 * re-hash, the image index from the registry digest header and a hash of the served index; install.sh
 * is only published as a file and is hashed locally. A sha256 that changes while its version does not
 * is refused. --check regenerates everything in memory and exits 1 with a diff when a committed file
 * differs; --verify does the same for the committed versions and re-downloads the k3s binaries.
 * The Traefik image tag is mutable (official images are rebuilt when their base image changes): a
 * committed digest the registry still serves for the same Traefik version is kept unless
 * --repin-image is given.
 */

