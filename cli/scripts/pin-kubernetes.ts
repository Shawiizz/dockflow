/** Retries transport failures, 429 and 5xx; any other answer is returned to the caller. */
async function request(url: string, init: RequestInit = {}): Promise<Response> {
  if (!url.startsWith('https://')) throw new PinError(`Refusing to download ${url} over a non-HTTPS URL`);
  const headers = new Headers(init.headers);
  if (!headers.has('User-Agent')) headers.set('User-Agent', 'dockflow-pin-kubernetes');
  let failure = '';
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const response = await fetch(url, { ...init, headers, redirect: 'follow', signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS) });
      if (response.status !== 429 && response.status < 500) return response;
      failure = `HTTP ${response.status}`;
    } catch (error) {
      failure = error instanceof Error ? error.message : String(error);
    }
    if (attempt < 3) await Bun.sleep(attempt * 2000);
  }
  throw new PinError(`${init.method ?? 'GET'} ${url} failed: ${failure}`);
}

async function fetchOk(url: string, init: RequestInit = {}): Promise<Response> {
  const response = await request(url, init);
  if (!response.ok) throw new PinError(`${init.method ?? 'GET'} ${url} answered HTTP ${response.status}`);
  return response;
}

async function fetchText(url: string, init: RequestInit = {}): Promise<string> {
  return (await fetchOk(url, init)).text();
}

async function fetchBytes(url: string): Promise<Uint8Array> {
  return new Uint8Array(await (await fetchOk(url)).arrayBuffer());
}

