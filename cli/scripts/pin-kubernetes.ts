async function k3sBinary(version: string, arch: Arch): Promise<Download> {
  const tag = encodeURIComponent(version);
  const listing = `sha256sum-${arch}.txt`;
  const source = `${listing} of k3s ${version}`;
  const sums = parseChecksums(await fetchText(`${K3S_RELEASES}/${tag}/${listing}`), source);
  const name = K3S_BINARY[arch];
  const sha256 = sums.get(name);
  if (sha256 === undefined) throw new PinError(`${source} has no entry for ${name}`);
  return { url: `${K3S_RELEASES}/${tag}/${name}`, sha256 };
}

async function resolveK3s(version: string, minimumServerVersion: string): Promise<K3sPins> {
  step(`k3s ${version}`);
  const binaries: Record<Arch, Download> = {
    amd64: await k3sBinary(version, 'amd64'),
    arm64: await k3sBinary(version, 'arm64'),
  };
  const url = `${K3S_SOURCES}/${encodeURIComponent(version)}/install.sh`;
  const installScript = { url, sha256: sha256Hex(await fetchBytes(url)) };
  return { version, minimumServerVersion, installScript, binaries };
}

async function helmArchive(version: string, arch: Arch): Promise<Download> {
  const name = `helm-${version}-linux-${arch}.tar.gz`;
  const url = `${HELM_DOWNLOADS}/${name}`;
  const sums = parseChecksums(await fetchText(`${url}.sha256sum`), `${name}.sha256sum`);
  const published = sums.get(name);
  if (published === undefined) throw new PinError(`${name}.sha256sum has no entry for ${name}`);
  const actual = sha256Hex(await fetchBytes(url));
  if (actual !== published) {
    throw new PinError(`${name}: ${name}.sha256sum says ${published}, the downloaded archive hashes to ${actual}`);
  }
  return { url, sha256: published };
}

async function resolveHelm(version: string): Promise<HelmPins> {
  step(`Helm ${version}`);
  return { version, archives: { amd64: await helmArchive(version, 'amd64'), arm64: await helmArchive(version, 'arm64') } };
}

async function chartIndexEntries(): Promise<unknown[]> {
  const index = asRecord(parseYaml(await fetchText(`${TRAEFIK_REPO}/index.yaml`)), `${TRAEFIK_REPO}/index.yaml`);
  const entries = asRecord(index.entries, `${TRAEFIK_REPO}/index.yaml entries`)[TRAEFIK_CHART];
  if (!Array.isArray(entries)) throw new PinError(`${TRAEFIK_REPO}/index.yaml lists no ${TRAEFIK_CHART} chart`);
  return entries;
}

async function resolveTraefikChart(version: string): Promise<ChartResolution> {
  step(`Traefik chart ${version}`);
  const entry = (await chartIndexEntries()).find((candidate) => isRecord(candidate) && candidate.version === version);
  if (!isRecord(entry)) throw new PinError(`${TRAEFIK_REPO}/index.yaml has no ${TRAEFIK_CHART} ${version}`);
  const urls: unknown = entry.urls;
  const listed = Array.isArray(urls) && typeof urls[0] === 'string' ? urls[0] : null;
  const digest = entry.digest;
  const appVersion = entry.appVersion;
  if (listed === null || typeof digest !== 'string' || !SHA256_RE.test(digest) || typeof appVersion !== 'string') {
    throw new PinError(`The index entry of ${TRAEFIK_CHART} ${version} lacks urls, a sha256 digest or appVersion`);
  }
  if (!PLAIN_VERSION_RE.test(appVersion)) throw new PinError(`${TRAEFIK_CHART} ${version} has appVersion ${appVersion}, not a vX.Y.Z tag`);
  const url = new URL(listed, `${TRAEFIK_REPO}/`).href;
  const archiveName = `${TRAEFIK_CHART}-${version}.tgz`;
  const archive = await fetchBytes(url);
  const sha256 = sha256Hex(archive);
  if (sha256 !== digest) {
    throw new PinError(`${archiveName}: the repository index digest is ${digest}, the downloaded archive hashes to ${sha256}`);
  }
  const files = readTarGz(archive, archiveName);
  const chartYaml = asRecord(parseYaml(fileText(files, `${TRAEFIK_CHART}/Chart.yaml`, archiveName)), `${archiveName} Chart.yaml`);
  if (chartYaml.version !== version || chartYaml.appVersion !== appVersion) {
    throw new PinError(
      `${archiveName}: Chart.yaml says version ${String(chartYaml.version)} appVersion ${String(chartYaml.appVersion)}, the repository index says ${version} ${appVersion}`,
    );
  }
  return { pin: { chart: TRAEFIK_CHART, repo: TRAEFIK_REPO, version, url, sha256, appVersion }, files };
}

async function registryToken(): Promise<string> {
  const body: unknown = JSON.parse(await fetchText(REGISTRY_TOKEN_URL));
  const token = isRecord(body) ? body.token : undefined;
  if (typeof token !== 'string' || token === '') throw new PinError(`Docker Hub returned no anonymous pull token for ${TRAEFIK_IMAGE_REPOSITORY}`);
  return token;
}

function registryHeaders(token: string): Record<string, string> {
  return { Authorization: `Bearer ${token}`, Accept: IMAGE_INDEX_TYPES };
}

async function currentTagDigest(tag: string, token: string): Promise<string> {
  const response = await fetchOk(`${REGISTRY}/v2/${TRAEFIK_IMAGE_REPOSITORY}/manifests/${tag}`, {
    method: 'HEAD',
    headers: registryHeaders(token),
  });
  const digest = response.headers.get('docker-content-digest');
  if (digest === null || !DIGEST_RE.test(digest)) throw new PinError(`docker.io/traefik:${tag}: the registry returned no image index digest`);
  return digest;
}

function platformEntry(manifests: unknown[], arch: Arch): Record<string, unknown> | undefined {
  for (const manifest of manifests) {
    if (!isRecord(manifest) || !isRecord(manifest.platform)) continue;
    if (manifest.platform.os === 'linux' && manifest.platform.architecture === arch) return manifest;
  }
  return undefined;
}

/** Empty when the registry serves the digest as a multi-arch index of Traefik <appVersion>. */
async function imageIndexProblems(digest: string, appVersion: string, token: string): Promise<string[]> {
  const url = `${REGISTRY}/v2/${TRAEFIK_IMAGE_REPOSITORY}/manifests/${digest}`;
  const response = await request(url, { headers: registryHeaders(token) });
  if (response.status === 404) return [`docker.io/traefik@${digest} is no longer served by the registry`];
  if (!response.ok) throw new PinError(`GET ${url} answered HTTP ${response.status}`);
  const body = new Uint8Array(await response.arrayBuffer());
  const problems: string[] = [];
  const served = `sha256:${sha256Hex(body)}`;
  if (served !== digest) problems.push(`docker.io/traefik@${digest}: the registry served an index hashing to ${served}`);
  const index: unknown = JSON.parse(decoder.decode(body));
  const manifests: unknown[] = isRecord(index) && Array.isArray(index.manifests) ? index.manifests : [];
  for (const arch of ARCHES) {
    const entry = platformEntry(manifests, arch);
    if (!entry) {
      problems.push(`docker.io/traefik@${digest} has no linux/${arch} image`);
      continue;
    }
    const version = isRecord(entry.annotations) ? entry.annotations['org.opencontainers.image.version'] : undefined;
    if (version !== undefined && version !== appVersion) {
      problems.push(`docker.io/traefik@${digest} linux/${arch} is Traefik ${String(version)}, not ${appVersion}`);
    }
  }
  return problems;
}

async function resolveImageDigest(
  appVersion: string,
  committed: TraefikPins | undefined,
  repinImage: boolean,
  notes: string[],
): Promise<string> {
  step(`Traefik image ${appVersion}`);
  const token = await registryToken();
  const tagDigest = await currentTagDigest(appVersion, token);
  const kept = committed !== undefined && committed.appVersion === appVersion && !repinImage ? committed.imageDigest : undefined;
  if (kept !== undefined && kept !== tagDigest) {
    const problems = await imageIndexProblems(kept, appVersion, token);
    if (problems.length === 0) {
      notes.push(
        `docker.io/traefik:${appVersion} now resolves to ${tagDigest} (the image was rebuilt); the pinned ${kept} is still served and was kept. Pass --repin-image to adopt the rebuild.`,
      );
      return kept;
    }
    notes.push(...problems, `The pin moves to the current digest of docker.io/traefik:${appVersion}.`);
  }
  const problems = await imageIndexProblems(tagDigest, appVersion, token);
  if (problems.length > 0) throw new PinError(problems.join('; '));
  return tagDigest;
}

/** The Middleware CRD `openAPIV3Schema` of the served version, reduced to what label coercion needs. */
function middlewareSchema(chart: ChartResolution): MiddlewareSchema {
  const archiveName = `${chart.pin.chart}-${chart.pin.version}.tgz`;
  const path = `${chart.pin.chart}/${MIDDLEWARE_CRD_FILE}`;
  const crds = parseAllDocuments(fileText(chart.files, path, archiveName)).map((document) => {
    if (document.errors.length > 0) throw new PinError(`${path}: ${document.errors[0].message}`);
    return document.toJS() as unknown;
  });
  const crd = crds.find((doc) => isRecord(doc) && doc.kind === 'CustomResourceDefinition' && isRecord(doc.metadata) && doc.metadata.name === MIDDLEWARE_CRD_NAME);
  const spec = asRecord(asRecord(crd, `${path} (${MIDDLEWARE_CRD_NAME})`).spec, `${path} spec`);
  if (typeof spec.group !== 'string' || !Array.isArray(spec.versions)) throw new PinError(`${path}: spec.group or spec.versions is missing`);
  const versions: unknown[] = spec.versions;
  const served = versions.filter((version) => isRecord(version) && version.served === true && version.storage === true);
  const version = served.length === 1 ? served[0] : undefined;
  if (!isRecord(version) || typeof version.name !== 'string') throw new PinError(`${path}: expected exactly one served storage version`);
  const openApi = asRecord(asRecord(version.schema, `${path} schema`).openAPIV3Schema, `${path} openAPIV3Schema`);
  const root = toNode(asRecord(openApi.properties, `${path} properties`).spec, 'spec', 'spec');
  if (root.type !== 'object' || root.properties === undefined) throw new PinError(`${path}: spec has no properties`);
  return { apiVersion: `${spec.group}/${version.name}`, types: root.properties };
}

// Validation-only keywords: label coercion only needs names and types (design-04 2.14.1 rule 4).
const IGNORED_SCHEMA_KEYS = new Set([
  'description',
  'format',
  'enum',
  'pattern',
  'minimum',
  'maximum',
  'exclusiveMinimum',
  'exclusiveMaximum',
  'minLength',
  'maxLength',
  'minItems',
  'maxItems',
  'minProperties',
  'maxProperties',
  'uniqueItems',
  'required',
  'default',
  'nullable',
  'x-kubernetes-validations',
  'x-kubernetes-list-type',
  'x-kubernetes-list-map-keys',
  'x-kubernetes-map-type',
]);
const STRUCTURAL_SCHEMA_KEYS = new Set(['type', 'items', 'properties', 'additionalProperties', 'x-kubernetes-preserve-unknown-fields']);

function toNode(schema: unknown, canonical: string, path: string): CrdNode {
  const node = asRecord(schema, path);
  if (node['x-kubernetes-int-or-string'] === true) return { canonical, type: 'int-or-string' };
  const unsupported = Object.keys(node).filter((key) => !IGNORED_SCHEMA_KEYS.has(key) && !STRUCTURAL_SCHEMA_KEYS.has(key));
  if (unsupported.length > 0) {
    throw new PinError(`${path}: unsupported schema keyword ${unsupported.join(', ')}; extend pin-kubernetes.ts before pinning this chart`);
  }
  const preserve = node['x-kubernetes-preserve-unknown-fields'] === true;
  if (node.type === undefined && preserve && node.properties === undefined) return { canonical, type: 'any' };
  switch (node.type) {
    case 'string':
    case 'integer':
    case 'number':
    case 'boolean':
      return { canonical, type: node.type };
    case 'array':
      return { canonical, type: 'array', items: toNode(node.items, '', `${path}[]`) };
    case 'object': {
      const result: CrdNode = { canonical, type: 'object' };
      if (isRecord(node.additionalProperties)) result.additionalProperties = toNode(node.additionalProperties, '', `${path}{}`);
      else if (node.additionalProperties === true || preserve) result.additionalProperties = { canonical: '', type: 'any' };
      if (node.properties !== undefined) result.properties = toProperties(node.properties, path);
      return result;
    }
    default:
      throw new PinError(`${path}: unsupported schema type ${JSON.stringify(node.type)}`);
  }
}

function toProperties(properties: unknown, path: string): Record<string, CrdNode> {
  const record = asRecord(properties, `${path}.properties`);
  const byKey = new Map<string, string>();
  for (const name of Object.keys(record)) {
    const key = name.toLowerCase();
    const other = byKey.get(key);
    if (other !== undefined) throw new PinError(`${path}: ${other} and ${name} only differ by case, so labels cannot tell them apart`);
    byKey.set(key, name);
  }
  const result: Record<string, CrdNode> = {};
  for (const key of [...byKey.keys()].sort(compareCodeUnits)) {
    const name = byKey.get(key) ?? key;
    result[key] = toNode(record[name], name, `${path}.${name}`);
  }
  return result;
}

