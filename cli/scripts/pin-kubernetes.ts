// Checksum files and archives

/** `<sha256>  <name>` lines (sha256sum output); a name listed twice with two hashes is refused. */
function parseChecksums(text: string, source: string): Map<string, string> {
  const sums = new Map<string, string>();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === '') continue;
    const match = /^([0-9A-Fa-f]{64})\s+\*?(\S.*)$/.exec(line);
    if (!match) throw new PinError(`${source}: unexpected line "${line}"`);
    const hash = match[1].toLowerCase();
    const name = match[2];
    const previous = sums.get(name);
    if (previous !== undefined && previous !== hash) throw new PinError(`${source} lists ${name} twice with different hashes`);
    sums.set(name, hash);
  }
  return sums;
}

const decoder = new TextDecoder();

function cString(bytes: Uint8Array): string {
  const end = bytes.indexOf(0);
  return decoder.decode(end < 0 ? bytes : bytes.subarray(0, end));
}

function tarSize(field: Uint8Array, name: string): number {
  if ((field[0] & 0x80) !== 0) throw new PinError(`${name}: base-256 tar sizes are not supported`);
  const text = cString(field).trim();
  const size = text === '' ? 0 : Number.parseInt(text, 8);
  if (!Number.isFinite(size)) throw new PinError(`${name}: invalid tar size field`);
  return size;
}

/** `<length> <key>=<value>\n` records of a PAX extended header */
function paxRecords(data: Uint8Array): Map<string, string> {
  const records = new Map<string, string>();
  let offset = 0;
  while (offset < data.length) {
    const space = data.indexOf(0x20, offset);
    if (space < 0) break;
    const length = Number.parseInt(decoder.decode(data.subarray(offset, space)), 10);
    if (!Number.isFinite(length) || length <= 0) break;
    const record = decoder.decode(data.subarray(space + 1, offset + length - 1));
    const eq = record.indexOf('=');
    if (eq > 0) records.set(record.slice(0, eq), record.slice(eq + 1));
    offset += length;
  }
  return records;
}

/** Regular files of a gzipped tar archive, keyed by path (ustar, GNU long names and PAX paths). */
function readTarGz(archive: Uint8Array, name: string): Map<string, Uint8Array> {
  const tar = new Uint8Array(gunzipSync(archive));
  const files = new Map<string, Uint8Array>();
  let offset = 0;
  let longName: string | null = null;
  let paxPath: string | null = null;
  while (offset + 512 <= tar.length) {
    const header = tar.subarray(offset, offset + 512);
    if (header.every((byte) => byte === 0)) break;
    const size = tarSize(header.subarray(124, 136), name);
    const type = String.fromCharCode(header[156]);
    const data = tar.subarray(offset + 512, offset + 512 + size);
    offset += 512 + Math.ceil(size / 512) * 512;
    if (type === 'x') {
      paxPath = paxRecords(data).get('path') ?? null;
      continue;
    }
    if (type === 'L') {
      longName = cString(data);
      continue;
    }
    if (type === 'g') continue;
    const prefix = cString(header.subarray(345, 500));
    const entry = paxPath ?? longName ?? (prefix === '' ? cString(header.subarray(0, 100)) : `${prefix}/${cString(header.subarray(0, 100))}`);
    paxPath = null;
    longName = null;
    if (type === '0' || type === '\0' || type === '7') files.set(entry, data);
  }
  return files;
}

function fileText(files: Map<string, Uint8Array>, path: string, archive: string): string {
  const data = files.get(path);
  if (!data) throw new PinError(`${archive} has no ${path}`);
  return decoder.decode(data);
}

