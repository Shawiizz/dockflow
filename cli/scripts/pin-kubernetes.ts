function isInline(node: CrdNode): boolean {
  if (node.properties !== undefined) return false;
  return (node.items === undefined || isInline(node.items)) && (node.additionalProperties === undefined || isInline(node.additionalProperties));
}

function emitNode(node: CrdNode, indent: string): string {
  const head = [`canonical: ${quote(node.canonical)}`, `type: ${quote(node.type)}`];
  if (isInline(node)) {
    const parts = [...head];
    if (node.items) parts.push(`items: ${emitNode(node.items, indent)}`);
    if (node.additionalProperties) parts.push(`additionalProperties: ${emitNode(node.additionalProperties, indent)}`);
    return `{ ${parts.join(', ')} }`;
  }
  const inner = `${indent}  `;
  const lines = ['{', ...head.map((part) => `${inner}${part},`)];
  if (node.items) lines.push(`${inner}items: ${emitNode(node.items, inner)},`);
  if (node.additionalProperties) lines.push(`${inner}additionalProperties: ${emitNode(node.additionalProperties, inner)},`);
  const entries = node.properties === undefined ? null : Object.entries(node.properties);
  if (entries !== null && entries.length === 0) lines.push(`${inner}properties: {},`);
  if (entries !== null && entries.length > 0) {
    lines.push(`${inner}properties: {`);
    for (const [key, child] of entries) lines.push(`${inner}  ${propertyKey(key)}: ${emitNode(child, `${inner}  `)},`);
    lines.push(`${inner}},`);
  }
  lines.push(`${indent}}`);
  return lines.join('\n');
}

